"""Schema + sanity tests for ml/artifacts/valuation-v2/effects.json (task 4d,
machine-readable "main drivers" for the product). Generated by
ml/train_valuation.py -> build_driver_effects(); this test validates the file that
script writes, not a pure function, so it is skipped (not failed) if the file has
never been generated in this checkout.
"""

import json
from pathlib import Path

import pytest

EFFECTS_JSON = Path(__file__).resolve().parents[1] / "artifacts" / "valuation-v2" / "effects.json"

REQUIRED_TOP_LEVEL_KEYS = {
    "version",
    "generated_at",
    "method",
    "data_period",
    "reference_categories",
    "area_specific_rule",
    "caveat_sv",
    "excluded_note",
    "effects",
}
REQUIRED_EFFECT_KEYS = {
    "id",
    "label_sv",
    "effekt_procent",
    "ci_low_procent",
    "ci_high_procent",
    "niva",
    "omrade",
    "n",
    "signifikant",
}

# ids the product is expected to be able to supply inputs for (hiss, balkong,
# rooms, floor, build year, avgift/avgift per m2, boarea) -- "omrade=" must never
# appear, per the brief ("area is the location itself, not a driver").
ALLOWED_ID_PREFIXES = ("elevator=", "balcony=", "rooms", "floor", "build_year", "fee_per_sqm", "boarea")


@pytest.fixture(scope="module")
def effects_doc() -> dict:
    if not EFFECTS_JSON.exists():
        pytest.skip(f"{EFFECTS_JSON} not generated yet -- run `ml/.venv/bin/python ml/train_valuation.py` first")
    return json.loads(EFFECTS_JSON.read_text(encoding="utf-8"))


class TestTopLevelSchema:
    def test_required_keys_present(self, effects_doc):
        assert REQUIRED_TOP_LEVEL_KEYS <= set(effects_doc.keys())

    def test_effects_is_a_non_empty_list(self, effects_doc):
        assert isinstance(effects_doc["effects"], list)
        assert len(effects_doc["effects"]) > 0

    def test_method_names_the_ols_companion_not_lightgbm(self, effects_doc):
        method = effects_doc["method"].lower()
        assert "ols" in method
        assert "not used for point predictions" in effects_doc["method"] or "companion" in method

    def test_data_period_and_caveat_present(self, effects_doc):
        assert effects_doc["data_period"]
        assert effects_doc["caveat_sv"]
        # caveat must be Swedish and must communicate "average, not this apartment"
        assert "genomsnitt" in effects_doc["caveat_sv"].lower()

    def test_reference_categories_present(self, effects_doc):
        assert effects_doc["reference_categories"]
        assert "hiss" in effects_doc["reference_categories"]
        assert "balkong" in effects_doc["reference_categories"]


class TestEffectSchema:
    def test_every_effect_has_required_keys(self, effects_doc):
        for e in effects_doc["effects"]:
            missing = REQUIRED_EFFECT_KEYS - set(e.keys())
            assert not missing, f"{e.get('id')}: missing keys {missing}"

    def test_id_and_label_are_nonempty_strings(self, effects_doc):
        for e in effects_doc["effects"]:
            assert isinstance(e["id"], str) and e["id"]
            assert isinstance(e["label_sv"], str) and e["label_sv"]

    def test_niva_is_stad_or_omrade(self, effects_doc):
        for e in effects_doc["effects"]:
            assert e["niva"] in ("stad", "omrade"), e

    def test_omrade_field_matches_niva(self, effects_doc):
        for e in effects_doc["effects"]:
            if e["niva"] == "omrade":
                assert e["omrade"], f"{e['id']}: area-specific effect must name its omrade"
            else:
                assert e["omrade"] is None, f"{e['id']}: city-wide effect must not have an omrade"

    def test_n_is_a_positive_int(self, effects_doc):
        for e in effects_doc["effects"]:
            assert isinstance(e["n"], int) and e["n"] > 0, e

    def test_percent_fields_are_numeric(self, effects_doc):
        for e in effects_doc["effects"]:
            for key in ("effekt_procent", "ci_low_procent", "ci_high_procent"):
                assert isinstance(e[key], (int, float)), f"{e['id']}.{key}"

    def test_signifikant_is_bool(self, effects_doc):
        for e in effects_doc["effects"]:
            assert isinstance(e["signifikant"], bool), e


class TestCiContainsPointEstimate:
    def test_ci_low_le_ci_high(self, effects_doc):
        for e in effects_doc["effects"]:
            assert e["ci_low_procent"] <= e["ci_high_procent"], e

    def test_point_estimate_within_ci(self, effects_doc):
        for e in effects_doc["effects"]:
            lo, point, hi = e["ci_low_procent"], e["effekt_procent"], e["ci_high_procent"]
            assert lo - 1e-6 <= point <= hi + 1e-6, e


class TestSignificanceFlagMatchesCi:
    def test_signifikant_iff_ci_excludes_zero(self, effects_doc):
        for e in effects_doc["effects"]:
            excludes_zero = e["ci_low_procent"] > 0 or e["ci_high_procent"] < 0
            assert e["signifikant"] == excludes_zero, e


class TestScopeRestrictedToProductInputs:
    def test_no_area_vs_area_driver(self, effects_doc):
        # area is the location itself, not a driver a buyer can act on/compare
        for e in effects_doc["effects"]:
            assert not e["id"].startswith("omrade="), e["id"]

    def test_every_id_maps_to_a_product_supplied_input(self, effects_doc):
        for e in effects_doc["effects"]:
            assert e["id"].startswith(ALLOWED_ID_PREFIXES), e["id"]

    def test_no_building_storeys_or_month_driver(self, effects_doc):
        # the product cannot supply these (see ml/artifacts/valuation-v2/MODEL_CARD.md)
        for e in effects_doc["effects"]:
            assert "storeys" not in e["id"] and "month" not in e["id"], e["id"]
